import assert from 'node:assert/strict';
const {createMotionGate,encodeMotion,decodeMotion}=await import('../../client/game-motion.js').catch(()=>({}));
assert.equal(typeof createMotionGate,'function','playable integration needs a real recipient lifecycle gate');
const gate=createMotionGate();
const row=(id,x)=>[id,'rifle',0,x,2,0,0,100,0,0,0,0,0,0,1,4,1,0,0];
gate.baseline({generation:'a',revision:1,tick:1},[row(1,1)]);
assert.equal(gate.accept(['a',1,3,1,3,2,0,0,4,1,0,0]),true);
gate.baseline({generation:'a',revision:1,tick:3},[row(1,3)]);
assert.equal(gate.accept(['a',1,3,1,99,2,0,0,4,1,0,0]),false,'equal-tick duplicate stays rejected after reliable catch-up');
gate.reset();gate.baseline({generation:'a',revision:1,tick:1},[row(1,1)]);
assert.equal(gate.accept(['a',1,3,1,3,2,0,0,4,1,0,0]),true);
let rows=[row(1,2)];gate.baseline({generation:'a',revision:1,tick:2},rows);gate.overlay(rows,2);assert.equal(rows[0][3],3,'stale reliable motion must not overwrite fresh datagram');
assert.equal(gate.accept(['a',1,2,1,9,2,0,0,4,1,0,0]),false,'reordered row rejected');
assert.equal(gate.accept(['a',1,4,2,9,2,0,0,4,1,0,0]),false,'unknown units never created');
gate.baseline({generation:'a',revision:2,tick:4},[]);
assert.equal(gate.accept(['a',1,5,1,9,2,0,0,4,1,0,0]),false,'hidden unit cannot resurrect');
gate.baseline({generation:'a',revision:3,tick:6},[row(1,6)]);
assert.equal(gate.accept(['a',2,8,1,9,2,0,0,4,1,0,0]),false,'old visibility epoch rejected');
gate.baseline({generation:'b',revision:1,tick:1},[row(1,1)]);
assert.equal(gate.accept(['a',3,9,1,9,2,0,0,4,1,0,0]),false,'old match/socket generation rejected');
assert.equal(gate.accept(['b',1,2,1,Infinity,2,0,0,4,1,0,0]),false);
assert.equal(gate.accept(['b',1,2,1,2,2,0,0,4,1,0,0]),true);
assert.deepEqual(decodeMotion(encodeMotion(['b',1,2,1,2,2,0,0,4,1,0,0])),['b',1,2,1,2,2,0,0,4,1,0,0]);
assert.throws(()=>decodeMotion(new Uint8Array(1001)));
gate.reset();assert.equal(gate.accept(['b',1,3,1,2,2,0,0,4,1,0,0]),false);
import {createGameTransport} from '../../client/game-transport.js';
assert.equal(createGameTransport({optIn:false}).mode,'WebSocket','default path needs no DOM, timer, socket or native dependency');
console.log('PASS game lifecycle, privacy, ordering, merge, reset and packet bounds');
