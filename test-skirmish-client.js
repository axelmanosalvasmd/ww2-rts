import assert from 'node:assert/strict';
import {availability,buyCount} from './client/availability.js';
import {CFG} from './shared/sim.js';
const row=(id,type,owner,built=1)=>[id,type,owner,20,20,0,0,100,0,0,0,0,0,0,built];
const s={mp:10000,mode:{kind:'conquest'},units:[row(1,'rifle',0),row(2,'barracks',0)]};
assert.equal(availability(s,CFG,{t:'buy',unit:'tank',slot:0}).ok,false,'missing Motor Pool locks card');
assert.equal(availability(s,CFG,{t:'buy',unit:'mg',slot:0}).ok,true);
assert.equal(availability(s,CFG,{t:'build',kind:'motorpool',ids:[1],slot:0}).ok,true);
assert.equal(availability(s,CFG,{t:'buy',unit:'mg',from:99,slot:0}).ok,false);
const h={...s,mode:{kind:'horde',slot:2},units:[row(1,'rifle',1),row(2,'barracks',0)]};
const shared={slot:1,teams:[0,0,1]};
assert.equal(availability(h,CFG,{...shared,t:'buy',unit:'mg'}).ok,true);
assert.ok(buyCount(h,CFG,{...shared,t:'buy',unit:'mg'},5)>0);
assert.equal(availability(h,CFG,{...shared,t:'build',kind:'motorpool',ids:[1]}).ok,true);
assert.equal(availability({...h,mode:{kind:'conquest'}},CFG,{...shared,t:'buy',unit:'mg'}).ok,false,'other modes do not share buildings');
assert.equal(availability({...s,mode:{kind:'tutorial'}},CFG,{t:'buy',unit:'tank',slot:0}).ok,true);
assert.equal(availability({...s,mode:{kind:'tutorial'}},CFG,{t:'build',kind:'motorpool',ids:[1],slot:0}).ok,false);
console.log('Skirmish client availability passed');
const {createOrders}=await import('./client/orders.js');
const {createSelection}=await import('./client/selection.js');
const {UNITS}=await import('./shared/sim.js');
const units=new Map([[1,{id:1,type:'rifle',owner:1,hp:100}],[2,{id:2,type:'barracks',owner:0,hp:500,built:1}]]), selected=new Set([1]), sent=[];
const orders=createOrders({units,selected,me:1,defs:UNITS,diggers:CFG.fortBuilders,builders:()=>CFG.fortBuilders,canUseBuilding:v=>v.owner===0,send:c=>sent.push(c),formation:()=>[],feedback:()=>{}});
orders.dispatch({building:units.get(2),ground:{x:20,z:20}});
assert.equal(sent[0]?.t,'assist','rifles right-click to repair shared facilities');
const selection=createSelection({units,selected,groups:{},owner:()=>1,definitions:UNITS,canUseBuilding:v=>v.owner===0,screenOf:()=>({x:10,y:10,front:true}),viewport:()=>({width:100,height:100}),center:()=>{}});
selection.click(units.get(2));assert.ok(selected.has(2),'Horde teammate can select shared building');
orders.dispatch({ground:{x:30,z:30}});assert.equal(sent.at(-1).t,'rally');
console.log('Skirmish selection and repair dispatch passed');
const {recruitAction}=await import('./client/availability.js');
assert.deepEqual(recruitAction(h,1,'mg',[2],[0,0,1]),{t:'buy',unit:'mg',from:2});
assert.deepEqual(recruitAction(h,1,'tank',[2],[0,0,1]),{t:'buy',unit:'tank'});
